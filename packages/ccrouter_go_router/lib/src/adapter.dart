/// Adapts CCRouter navigation requests to an externally configured [GoRouter].
///
/// The application owns the [router] and supplies its `GoRoute` page builders.
/// This adapter only translates validated CCRouter operations; it does not
/// generate page widgets, retain a global `BuildContext`, or dispose the
/// externally supplied router. GoRouter route paths should match the primary
/// path patterns generated by the registered route contracts.
///
/// Modal bottom sheets and dialogs are supported when their bound [GoRoute]
/// supplies a custom `pageBuilder` returning the corresponding exported modal
/// Page type. The adapter does not rewrite application-owned GoRoutes.
final class CCGoRouterAdapter
    implements
        CCNavigationAdapter,
        CCNavigationAdapterHostBinding,
        CCNavigationAdapterCapabilitySource,
        CCNavigationBackendEventSource,
        CCNavigationBackendSnapshotSource,
        CCNavigationPopCoordinator,
        CCNavigationPopGuardBinding,
        CCNavigationPredictiveBackSourceProvider {
  /// Creates an adapter around an application-owned [router].
  factory CCGoRouterAdapter({
    required GoRouter router,
    Iterable<CCGoRouterRouteBinding> bindings = const [],
    Iterable<CCGoRouterShellBinding> shells = const [],
    CCNavigationHost? host,
    Map<String, GlobalKey<NavigatorState>> navigatorKeys = const {},
    Iterable<CCGoRouterNavigationObserver> observers = const [],
    int lifecycleEventCapacity = 1000,
    bool enablePredictiveBack = false,
  }) {
    final shellList = List<CCGoRouterShellBinding>.unmodifiable(shells);
    final observerList = List<CCGoRouterNavigationObserver>.unmodifiable(
      observers,
    );
    if (host != null && navigatorKeys.isNotEmpty) {
      throw ArgumentError.value(
        navigatorKeys,
        'navigatorKeys',
        'Supply either a CCNavigationHost or legacy navigatorKeys, not both.',
      );
    }
    if (host != null &&
        !identical(host.navigatorKey, router.routerDelegate.navigatorKey)) {
      throw ArgumentError.value(
        host,
        'host',
        'The Host root Navigator key must be used by the supplied GoRouter.',
      );
    }
    final hostId = host?.id ?? 'default';
    final mergedNavigatorKeys = _mergeNavigatorKeys(
      host?.navigatorKeys ?? navigatorKeys,
      shellList,
    );
    if (host != null) {
      _validateHostNavigatorKeys(host, mergedNavigatorKeys);
    }
    _validateObserverBindings(hostId, mergedNavigatorKeys, observerList);
    return CCGoRouterAdapter._(
      router: router,
      bindings: bindings,
      shells: shellList,
      hostId: hostId,
      navigatorKeys: mergedNavigatorKeys,
      observers: observerList,
      lifecycleEventCapacity: lifecycleEventCapacity,
      enablePredictiveBack: enablePredictiveBack,
    );
  }

  /// Internal constructor used after iterable inputs have been snapshotted.
  CCGoRouterAdapter._({
    required GoRouter router,
    required Iterable<CCGoRouterRouteBinding> bindings,
    required Iterable<CCGoRouterShellBinding> shells,
    required String hostId,
    required Map<String, GlobalKey<NavigatorState>> navigatorKeys,
    required Iterable<CCGoRouterNavigationObserver> observers,
    required int lifecycleEventCapacity,
    required bool enablePredictiveBack,
  }) : _router = router,
       _bindings = List.unmodifiable(bindings),
       _shellBindings = List.unmodifiable(shells),
       _hostId = hostId,
       _navigatorKeys = navigatorKeys,
       _observers = List.unmodifiable(observers),
       _lifecycleEventCapacity = lifecycleEventCapacity,
       _predictiveBackBridge = enablePredictiveBack
           ? CCGoRouterPredictiveBackBridge._()
           : null {
    if (lifecycleEventCapacity < 0) {
      throw ArgumentError.value(
        lifecycleEventCapacity,
        'lifecycleEventCapacity',
        'Capacity cannot be negative.',
      );
    }
    _foreignRouteBridge = CCGoRouterForeignRouteBridge._(
      allocateBackendEntryId: _nextBackendEntryId,
      publish: _recordForeignBridgeEvent,
      publishOpaque: _recordOpaqueBridgeEvent,
    );
    for (final observer in _observers) {
      _observerRemovers.add(observer.addListener(_recordLifecycleEvent));
    }
    _router.routerDelegate.addListener(_recordRouterConfigurationChange);
  }

  /// GoRouter instance that receives translated navigation operations.
  GoRouter get router => _router;

  /// Backend capabilities exposed for Host setup and diagnostics.
  ///
  /// The supplied GoRouter remains application-owned. Predictive-back support
  /// is reported only when the host opts into `enablePredictiveBack` and uses
  /// [predictiveBackBridge] to forward platform phases. Its current match
  /// tree and initial route-information location can still be reported as
  /// opaque backend entries when predictive back is disabled.
  @override
  CCNavigationAdapterCapabilities get capabilities =>
      CCNavigationAdapterCapabilities(
        supportsBackendVisibilityObservation:
            _hasCompleteVisibilityObserverCoverage,
        supportsNestedNavigators: true,
        supportsStatefulShell: true,
        supportsModalRoutes: true,
        supportsPredictiveBack: _predictiveBackBridge != null,
        supportsManagedPopObservation: true,
      );

  /// Host-only bridge for explicitly integrated third-party Navigator routes.
  ///
  /// Application composition roots may use this when an independent Navigator
  /// cannot install [CCGoRouterNavigationObserver]. Business features should
  /// continue to navigate only through `CCRouter.navigator`.
  CCGoRouterForeignRouteBridge get foreignRouteBridge => _foreignRouteBridge;

  /// Host-only predictive-back bridge, when explicitly enabled at creation.
  ///
  /// The bridge reports platform gesture phases; it does not execute a Pop.
  /// The host must report a committed phase only after its Navigator has
  /// completed the corresponding backend removal.
  CCGoRouterPredictiveBackBridge? get predictiveBackBridge =>
      _predictiveBackBridge;

  /// Optional predictive-back source consumed by Runtime during initialization.
  @override
  CCNavigationPredictiveBackSource? get predictiveBackSource =>
      _predictiveBackBridge;

  /// Binds Runtime Pop policy to the optional platform back bridge.
  ///
  /// The binding is host infrastructure. Business navigation continues to use
  /// `CCRouter.navigator`, whose Pop operations evaluate the same guards before
  /// entering this Adapter.
  @override
  void bindPopGuardEvaluator(CCPopGuardEvaluator? evaluator) {
    _predictiveBackBridge?._bindPopGuardEvaluator(evaluator);
  }

  /// Reads GoRouter's pre-existing match tree as opaque backend entries.
  ///
  /// The initial match tree has no CCRouter `navigationId`, so every entry is
  /// intentionally classified as opaque. Runtime can diagnose the existing
  /// GoRouter stack and its Shell Outlets, but it cannot create a managed
  /// RouteEntry or typed result channel from this snapshot.
  @override
  List<CCNavigationBackendEntrySnapshot> readInitialBackendSnapshot() {
    _ensureAvailable();
    final snapshots = <CCNavigationBackendEntrySnapshot>[];
    _collectInitialMatches(
      _router.routerDelegate.currentConfiguration.matches,
      snapshots,
      outlet: 'root',
    );
    if (snapshots.isEmpty) {
      final initialUri = _router.routeInformationProvider.value.uri;
      if (initialUri.toString().isNotEmpty) {
        snapshots.add(
          CCNavigationBackendEntrySnapshot(
            backendEntryId: _nextBackendEntryId(),
            owner: CCBackendEntryOwner.opaque,
            hostId: _hostId,
            navigatorOutlet: 'root',
            location: initialUri.toString(),
          ),
        );
      }
    }
    _unboundInitialBackendEntries
      ..clear()
      ..addAll(
        snapshots.map(
          (snapshot) => _CCInitialBackendEntry(
            backendEntryId: snapshot.backendEntryId,
            navigatorOutlet: snapshot.navigatorOutlet,
            location: snapshot.location,
          ),
        ),
      );
    return List.unmodifiable(snapshots);
  }

  /// Application-owned GoRouter backend.
  final GoRouter _router;

  /// Stable Flutter Host identity served by this Adapter instance.
  final String _hostId;

  /// Adapter-owned third-party route reporting bridge.
  late final CCGoRouterForeignRouteBridge _foreignRouteBridge;

  /// Explicitly enabled host bridge for platform predictive-back phases.
  final CCGoRouterPredictiveBackBridge? _predictiveBackBridge;

  /// Component route bindings used to validate the application route table.
  final List<CCGoRouterRouteBinding> _bindings;

  /// Application-owned Shell bindings used to validate placement metadata.
  final List<CCGoRouterShellBinding> _shellBindings;

  /// Runtime Shell contracts accepted during initialization.
  final List<CCNavigationShell> _runtimeShells = [];

  /// Application-owned Navigator keys indexed by CCRouter Outlet name.
  final Map<String, GlobalKey<NavigatorState>> _navigatorKeys;

  /// Observers supplied by the application-owned GoRouter tree.
  final List<CCGoRouterNavigationObserver> _observers;

  /// Maximum number of lifecycle events retained for diagnostics.
  final int _lifecycleEventCapacity;

  /// Listener removers registered against [_observers].
  final List<void Function()> _observerRemovers = [];

  /// Last foreground Outlet reported for each Stateful Shell.
  final Map<String, String> _activeOutletsByShell = {};

  /// Runtime listeners receiving backend Navigator observations.
  final Set<CCNavigationBackendEventListener> _backendListeners = {};

  /// Bounded lifecycle events emitted by configured Navigator observers.
  final List<CCGoRouterNavigationEvent> _lifecycleEvents = [];

  /// Route metadata accepted by the Runtime during initialization.
  final List<CCNavigationRoute> _routes = [];

  /// Entries observed through operations issued by this adapter.
  final List<_CCGoRouterEntry> _entries = [];

  /// Adapter-local prefix used to keep backend identities unique across
  /// multiple GoRouter adapters in one process.
  final String _backendAdapterId =
      '${DateTime.now().microsecondsSinceEpoch}-${identityHashCode(Object())}';

  /// Monotonic backend Entry sequence for this adapter instance.
  int _backendEntrySequence = 0;

  /// Monotonic backend operation sequence for this adapter instance.
  int _backendOperationSequence = 0;

  /// Identity map from Flutter Routes to backend Entry IDs.
  final Expando<String> _backendRouteIds = Expando<String>();

  /// Initial opaque entries waiting for their first concrete Flutter Route.
  ///
  /// Runtime imports these entries before the Navigator is mounted. Reusing
  /// their identity for the first matching observer callback prevents the same
  /// initial page from appearing once as opaque and again as foreign.
  final List<_CCInitialBackendEntry> _unboundInitialBackendEntries = [];

  /// Backend Entry ID observed by the most recent Pop callback.
  String? _lastPoppedBackendEntryId;

  /// Ownership observed for the most recent Pop callback.
  CCPopRemovedOwner _lastPoppedOwner = CCPopRemovedOwner.none;

  /// Managed backend IDs indexed by their Runtime navigation identity.
  final Map<String, String> _backendIdsByNavigationId = {};

  /// Backend transitions expected from the next adapter-owned operations.
  ///
  /// Navigator observer callbacks may arrive after the imperative call has
  /// returned, so a short-lived queue is safer than a synchronous mutation
  /// flag for distinguishing adapter-owned transitions from external changes.
  final List<CCGoRouterNavigationEventKind> _expectedBackendEvents = [];

  /// Whether [initialize] completed successfully.
  bool _initialized = false;

  /// Whether [dispose] permanently closed the adapter.
  bool _disposed = false;

  /// Whether the adapter is initialized and has not been disposed.
  bool get isInitialized => _initialized && !_disposed;

  /// Immutable route metadata accepted during initialization.
  List<CCNavigationRoute> get routes => List.unmodifiable(_routes);

  /// Application-owned GoRouter bindings supplied for Runtime route IDs.
  List<CCGoRouterRouteBinding> get bindings => _bindings;

  /// Navigator keys used to resolve explicit non-root Outlet targets.
  Map<String, GlobalKey<NavigatorState>> get navigatorKeys => _navigatorKeys;

  /// Stable Flutter Host identity associated with backend observations.
  ///
  /// Use this only for Host diagnostics and Adapter configuration validation;
  /// business navigation continues to target generated route contracts.
  @override
  String get hostId => _hostId;

  /// Application-owned Shell bindings supplied for Runtime route placement.
  List<CCGoRouterShellBinding> get shells => _shellBindings;

  /// Runtime Shell contracts validated against application-owned bindings.
  List<CCNavigationShell> get shellContracts =>
      List.unmodifiable(_runtimeShells);

  /// Navigator observers subscribed by this Adapter.
  List<CCGoRouterNavigationObserver> get observers => _observers;

  /// Bounded snapshot of observed Navigator lifecycle events.
  List<CCGoRouterNavigationEvent> get lifecycleEvents =>
      List.unmodifiable(_lifecycleEvents);

  /// Whether every managed route Outlet has a confirmed top-route observer.
  ///
  /// Partial observer coverage deliberately disables delayed Runtime arrival
  /// for the whole Adapter. This preserves compatibility for unobserved routes
  /// instead of leaving their RouteEntries permanently in the pushed state.
  bool get _hasCompleteVisibilityObserverCoverage {
    if (_observers.isEmpty) return false;
    return _routes.every((route) {
      final outlet = route.placement.navigatorOutlet;
      return _observers.any(
        (observer) => observer.hostId == _hostId && observer.outlet == outlet,
      );
    });
  }

  /// Subscribes to backend Navigator transitions observed by this adapter.
  ///
  /// Runtime uses this optional adapter capability to expose user gesture,
  /// system back, and application-owned stack changes without importing
  /// Flutter types into Core. The returned callback removes the listener.
  @override
  void Function() addBackendEventListener(
    CCNavigationBackendEventListener listener,
  ) {
    _backendListeners.add(listener);
    return () => _backendListeners.remove(listener);
  }

  /// Initializes the adapter with Runtime-validated route metadata.
  ///
  /// The adapter validates presentation capabilities before accepting any
  /// navigation. GoRouter remains responsible for matching and rendering the
  /// application's concrete `GoRoute` tree.
  @override
  void initialize(
    List<CCNavigationRoute> routes, {
    List<CCNavigationShell> shells = const [],
  }) {
    _ensureNotDisposed();
    if (_initialized) {
      throw const CCNavigationAdapterError(
        'The GoRouter navigation adapter is already initialized.',
      );
    }
    final routeIds = <String>{};
    _validateShellBindings(shells);
    _runtimeShells
      ..clear()
      ..addAll(shells);
    for (final route in routes) {
      if (!routeIds.add(route.routeId)) {
        throw CCNavigationAdapterError(
          'Duplicate route ID "${route.routeId}" supplied to GoRouter.',
        );
      }
      switch (route.presentation) {
        case final CCPagePresentation presentation:
          _validatePresentationBinding(
            route.routeId,
            CCGoRouterPresentationType.page,
          );
          if (_requiresCustomPage(presentation)) {
            _ensureCustomPage(route.routeId);
          }
          break;
        case CCModalBottomSheetPresentation():
          _validatePresentationBinding(
            route.routeId,
            CCGoRouterPresentationType.bottomSheet,
          );
          _ensureCustomModalPage(route.routeId);
          break;
        case CCDialogPresentation():
          _validatePresentationBinding(
            route.routeId,
            CCGoRouterPresentationType.dialog,
          );
          _ensureCustomModalPage(route.routeId);
      }
      _validatePlacement(route);
    }
    _validateBindings(routeIds);
    _routes
      ..clear()
      ..addAll(routes);
    _initialized = true;
  }

  /// Executes one validated request through GoRouter.
  @override
  Future<Object?> navigate(CCNavigationRequest request) {
    _ensureAvailable();
    _ensureRequestHost(request);
    _ensureRoute(request.routeId);
    final location = _locationFor(request.uri);
    switch (request.operation) {
      case CCNavigationOperation.push:
        return _push(request, location);
      case CCNavigationOperation.replace:
        return _replace(request, location);
      case CCNavigationOperation.go:
      case CCNavigationOperation.reset:
        _expectBackendEvent(CCGoRouterNavigationEventKind.remove);
        _expectBackendEvent(CCGoRouterNavigationEventKind.push);
        _router.go(location, extra: request.extra);
        _replaceTrackedStack(request);
        return Future<Object?>.value();
      case CCNavigationOperation.open:
        if (request.openMode == CCDeepLinkOpenMode.go) {
          _expectBackendEvent(CCGoRouterNavigationEventKind.remove);
          _expectBackendEvent(CCGoRouterNavigationEventKind.push);
          _router.go(location, extra: request.extra);
          _replaceTrackedStack(request);
          return Future<Object?>.value();
        }
        return _open(request, location);
    }
  }

  /// Attempts to pop the active GoRouter Navigator route.
  ///
  /// A successful `Navigator.maybePop` can consume a LocalHistoryEntry or a
  /// foreign PopupRoute instead of an adapter-owned route. The managed entry
  /// list is therefore not changed by position here; a result-bearing managed
  /// Push removes its own entry when the GoRouter Future completes.
  @override
  Future<bool> maybePop({Object? result}) async {
    final outcome = await maybePopOutcome(result: result);
    return outcome.handled;
  }

  /// Coordinates a GoRouter Pop with best-effort backend identity correlation.
  ///
  /// A Pop with no Navigator observer event is reported as handled with owner
  /// `none`; this is the expected result for LocalHistoryEntry and opaque
  /// backend guards, and it never causes Runtime to remove a managed entry.
  @override
  Future<CCPopOutcome> maybePopOutcome({Object? result}) async {
    _ensureAvailable();
    final navigator = _activeNavigator;
    if (navigator == null) return CCPopOutcome(handled: false, hostId: _hostId);
    _lastPoppedBackendEntryId = null;
    _lastPoppedOwner = CCPopRemovedOwner.none;
    _expectBackendEvent(CCGoRouterNavigationEventKind.pop);
    final didPop = await navigator.maybePop<Object?>(result);
    // LocalHistoryEntry consumption emits no NavigatorObserver Pop. Remove an
    // unmatched expectation before it can misclassify a later foreign Pop.
    _discardExpectedBackendEvent(CCGoRouterNavigationEventKind.pop);
    if (!didPop) return CCPopOutcome(handled: false, hostId: _hostId);
    return CCPopOutcome(
      handled: true,
      removedBackendEntryId: _lastPoppedBackendEntryId,
      removedOwner: _lastPoppedOwner,
      hostId: _hostId,
    );
  }

  /// Pops the active GoRouter Navigator route with an optional result.
  @override
  void pop({Object? result}) {
    final outcome = popOutcome(result: result);
    if (!outcome.handled) {
      throw const CCNavigationAdapterError(
        'GoRouter has no removable active Navigator route.',
      );
    }
  }

  /// Pops the active GoRouter route and reports backend ownership.
  ///
  /// Navigator observer callbacks are emitted while the adapter's tracked
  /// entries still contain the route, allowing a direct business Pop to
  /// distinguish a foreign Popup/Route from a CCRouter-managed entry.
  @override
  CCPopOutcome popOutcome({Object? result}) {
    _ensureAvailable();
    final navigator = _activeNavigator;
    if (navigator == null || !navigator.canPop()) {
      return CCPopOutcome(handled: false, hostId: _hostId);
    }
    _lastPoppedBackendEntryId = null;
    _lastPoppedOwner = CCPopRemovedOwner.none;
    final removedEntry = _entries.isEmpty ? null : _entries.last;
    _expectBackendEvent(CCGoRouterNavigationEventKind.pop);
    navigator.pop<Object?>(result);
    _discardExpectedBackendEvent(CCGoRouterNavigationEventKind.pop);
    if (_lastPoppedOwner == CCPopRemovedOwner.managed && removedEntry != null) {
      _removeTrackedEntry(removedEntry);
    }
    return CCPopOutcome(
      handled: true,
      removedBackendEntryId: _lastPoppedBackendEntryId,
      removedOwner: _lastPoppedOwner,
      hostId: _hostId,
    );
  }

  /// Returns whether GoRouter can pop its current Navigator stack.
  @override
  bool canPop() {
    _ensureAvailable();
    return _activeNavigator?.canPop() ?? false;
  }

  /// Permanently closes adapter-owned state without disposing [router].
  ///
  /// Pending result-bearing Push and Replace operations fail with
  /// [CCNavigationAdapterError] so callers never wait forever during Runtime
  /// shutdown. Fire-and-forget dynamic opens and location changes have no
  /// exposed result channel and therefore do not emit an unhandled error.
  @override
  void dispose() {
    if (_disposed) return;
    _disposed = true;
    _initialized = false;
    final disposeError = const CCNavigationAdapterError(
      'GoRouter adapter was disposed before navigation completed.',
    );
    final disposeStackTrace = StackTrace.current;
    for (final entry in _entries) {
      entry.completeError(disposeError, disposeStackTrace);
    }
    for (final remove in _observerRemovers) {
      remove();
    }
    _router.routerDelegate.removeListener(_recordRouterConfigurationChange);
    _observerRemovers.clear();
    _backendListeners.clear();
    _routes.clear();
    _runtimeShells.clear();
    _entries.clear();
    _foreignRouteBridge._dispose();
    _predictiveBackBridge?._dispose();
    _backendIdsByNavigationId.clear();
    _unboundInitialBackendEntries.clear();
    _expectedBackendEvents.clear();
    _activeOutletsByShell.clear();
    _lifecycleEvents.clear();
  }

  /// Pushes one location and removes its tracked entry when it completes.
  Future<Object?> _push(CCNavigationRequest request, String location) {
    return _pushTracked(request, location, exposesResult: true);
  }

  /// Pushes and tracks one location with an optional business result channel.
  Future<Object?> _pushTracked(
    CCNavigationRequest request,
    String location, {
    required bool exposesResult,
  }) {
    final backendEntryId = _nextBackendEntryId();
    _backendIdsByNavigationId[request.navigationId] = backendEntryId;
    final entry = _CCGoRouterEntry(
      request,
      backendEntryId,
      exposesResult: exposesResult,
    );
    _entries.add(entry);
    _expectBackendEvent(CCGoRouterNavigationEventKind.push);
    final result = _router.push<Object?>(location, extra: request.extra);
    result.then<void>(
      (value) {
        entry.completeResult(value);
        _removeTrackedEntry(entry);
        _discardExpectedBackendEvent(CCGoRouterNavigationEventKind.push);
      },
      onError: (Object error, StackTrace stackTrace) {
        entry.completeError(error, stackTrace);
        _removeTrackedEntry(entry);
        _discardExpectedBackendEvent(CCGoRouterNavigationEventKind.push);
      },
    );
    return entry.result;
  }

  /// Pushes an internally resolved location without exposing a result Future.
  ///
  /// Runtime `open` completes after backend acceptance, while the created
  /// route remains tracked until its later Pop. This preserves the same
  /// push-like stack semantics as the in-memory Adapter without turning an
  /// untyped dynamic location into a result-bearing business API. An Open
  /// request explicitly using [CCDeepLinkOpenMode.go] takes the declarative
  /// location path in [navigate] instead.
  Future<Object?> _open(CCNavigationRequest request, String location) {
    return _pushTracked(request, location, exposesResult: false);
  }

  /// Replaces the tracked top entry with a new GoRouter page identity.
  ///
  /// GoRouter's `replace` deliberately reuses the existing Page key and keeps
  /// its State. CCRouter replacement closes the previous Route Scope, so it
  /// maps to `pushReplacement` to preserve Flutter's ordinary replacement
  /// lifecycle even when the destination has the same route ID.
  Future<Object?> _replace(CCNavigationRequest request, String location) {
    final replaced = _removeTrackedEntry();
    replaced?.completeResult(null);
    final backendEntryId = _nextBackendEntryId();
    _backendIdsByNavigationId[request.navigationId] = backendEntryId;
    final entry = _CCGoRouterEntry(
      request,
      backendEntryId,
      exposesResult: true,
    );
    _entries.add(entry);
    _expectBackendEvent(CCGoRouterNavigationEventKind.replace);
    final result = _router.pushReplacement<Object?>(
      location,
      extra: request.extra,
    );
    result.then<void>(
      (value) {
        entry.completeResult(value);
        _removeTrackedEntry(entry);
        _discardExpectedBackendEvent(CCGoRouterNavigationEventKind.replace);
      },
      onError: (Object error, StackTrace stackTrace) {
        entry.completeError(error, stackTrace);
        _removeTrackedEntry(entry);
        _discardExpectedBackendEvent(CCGoRouterNavigationEventKind.replace);
      },
    );
    return entry.result;
  }

  /// Replaces the locally observed stack after a GoRouter location change.
  ///
  /// Existing result-bearing entries complete with `null`, matching normal
  /// declarative history removal, before their identity mappings are released.
  void _replaceTrackedStack(CCNavigationRequest request) {
    for (final entry in _entries) {
      entry.completeResult(null);
      _backendIdsByNavigationId.remove(entry.request.navigationId);
    }
    final backendEntryId = _nextBackendEntryId();
    _backendIdsByNavigationId[request.navigationId] = backendEntryId;
    _entries
      ..clear()
      ..add(_CCGoRouterEntry(request, backendEntryId, exposesResult: false));
  }

  /// Returns or allocates the adapter identity for one backend Route object.
  String _backendEntryIdFor(Route<dynamic> route) =>
      _backendRouteIds[route] ??= _nextBackendEntryId();

  /// Allocates one adapter-scoped backend Entry identity.
  String _nextBackendEntryId() =>
      '$_backendAdapterId-entry-${++_backendEntrySequence}';

  /// Removes one locally observed entry, or the current top entry.
  _CCGoRouterEntry? _removeTrackedEntry([_CCGoRouterEntry? entry]) {
    if (_entries.isEmpty) return null;
    if (entry == null) {
      final removed = _entries.removeLast();
      _backendIdsByNavigationId.remove(removed.request.navigationId);
      return removed;
    } else {
      if (_entries.remove(entry)) {
        _backendIdsByNavigationId.remove(entry.request.navigationId);
        return entry;
      }
    }
    return null;
  }

  /// Records one backend transition expected from an Adapter-owned operation.
  void _expectBackendEvent(CCGoRouterNavigationEventKind kind) {
    _expectedBackendEvents.add(kind);
  }

  /// Consumes one matching expected transition, if present.
  bool _consumeExpectedBackendEvent(CCGoRouterNavigationEventKind kind) {
    final index = _expectedBackendEvents.indexOf(kind);
    if (index == -1) return false;
    _expectedBackendEvents.removeAt(index);
    return true;
  }

  /// Removes one expected transition when the backend reports no mutation.
  void _discardExpectedBackendEvent(CCGoRouterNavigationEventKind kind) {
    final index = _expectedBackendEvents.indexOf(kind);
    if (index != -1) _expectedBackendEvents.removeAt(index);
  }

  /// Converts an absolute URI into the path location consumed by GoRouter.
  String _locationFor(Uri uri) {
    if (!uri.hasScheme && !uri.hasAuthority) return uri.toString();
    return Uri(
      path: uri.path.isEmpty ? '/' : uri.path,
      query: uri.hasQuery ? uri.query : null,
      fragment: uri.hasFragment ? uri.fragment : null,
    ).toString();
  }

  /// Rejects initialization after permanent adapter disposal.
  void _ensureNotDisposed() {
    if (_disposed) {
      throw const CCNavigationAdapterError(
        'The GoRouter navigation adapter has been disposed.',
      );
    }
  }

  /// Rejects operations before initialization or after disposal.
  void _ensureAvailable() {
    if (!isInitialized) {
      throw const CCNavigationAdapterError(
        'The GoRouter navigation adapter is not active.',
      );
    }
  }

  /// Verifies that Runtime supplied the target route during initialization.
  void _ensureRoute(String routeId) {
    if (!_routes.any((route) => route.routeId == routeId)) {
      throw CCNavigationAdapterError(
        'Route "$routeId" was not supplied to the GoRouter adapter.',
      );
    }
  }

  /// Rejects a request resolved for another navigation Host.
  void _ensureRequestHost(CCNavigationRequest request) {
    if (request.hostId != _hostId) {
      throw CCNavigationAdapterError(
        'Navigation request "${request.navigationId}" targets Host '
        '"${request.hostId}", but this Adapter serves Host "$_hostId".',
      );
    }
  }

  /// Validates the optional binding set against Runtime route IDs.
  void _validateBindings(Set<String> routeIds) {
    if (_bindings.isEmpty) return;
    final bindingIds = <String>{};
    for (final binding in _bindings) {
      if (!bindingIds.add(binding.routeId)) {
        throw CCNavigationAdapterError(
          'Duplicate GoRouter binding for route "${binding.routeId}".',
        );
      }
      if (!routeIds.contains(binding.routeId)) {
        throw CCNavigationAdapterError(
          'GoRouter binding "${binding.routeId}" has no Runtime route.',
        );
      }
    }
    final missing = routeIds.difference(bindingIds);
    if (missing.isNotEmpty) {
      final ids = missing.toList()..sort();
      throw CCNavigationAdapterError(
        'Runtime routes have no GoRouter binding: ${ids.join(', ')}.',
      );
    }
  }

  /// Finds the application-owned binding for [routeId], if one was supplied.
  CCGoRouterRouteBinding? _bindingFor(String routeId) {
    for (final binding in _bindings) {
      if (binding.routeId == routeId) return binding;
    }
    return null;
  }

  /// Ensures one binding declares the same presentation family as Runtime.
  void _validatePresentationBinding(
    String routeId,
    CCGoRouterPresentationType expected,
  ) {
    final binding = _bindingFor(routeId);
    if (binding != null && binding.presentationType != expected) {
      throw CCNavigationAdapterError(
        'GoRouter binding "$routeId" declares '
        '${binding.presentationType.name}, but Runtime requires '
        '${expected.name}.',
      );
    }
  }

  /// Requires the custom page builder needed to preserve modal semantics.
  void _ensureCustomModalPage(String routeId) {
    final binding = _bindingFor(routeId);
    if (binding == null || !binding.hasCustomPageBuilder) {
      throw CCNavigationAdapterError(
        'Modal route "$routeId" requires a GoRouter binding with a custom '
        'pageBuilder returning the matching CCRouter modal Page.',
      );
    }
  }

  /// Requires a custom page builder when a plain GoRoute builder cannot retain
  /// the route contract's page family, transition, or opacity semantics.
  void _ensureCustomPage(String routeId) {
    final binding = _bindingFor(routeId);
    if (binding == null || !binding.hasCustomPageBuilder) {
      throw CCNavigationAdapterError(
        'Page route "$routeId" requires a GoRouter binding with a custom '
        'pageBuilder returning ccGoRouterPage(...).',
      );
    }
  }

  /// Returns whether a normal GoRoute builder would lose page semantics.
  bool _requiresCustomPage(CCPagePresentation presentation) =>
      presentation.routeType != CCPageRouteType.platformDefault ||
      presentation.transition != CCPageTransitionType.platformDefault ||
      !presentation.opaque ||
      presentation.fullscreenDialog;

  /// Rejects Shell and non-root Outlet metadata until a matching binding is
  /// supplied by the GoRouter Shell integration.
  void _validatePlacement(CCNavigationRoute route) {
    final placement = route.placement;
    if (placement.hostId != 'default' && placement.hostId != _hostId) {
      throw CCNavigationAdapterError(
        'GoRouter route "${route.routeId}" targets Host '
        '"${placement.hostId}", but this Adapter serves Host "$_hostId".',
      );
    }
    if (placement.navigatorOutlet != 'root' &&
        !_navigatorKeys.containsKey(placement.navigatorOutlet)) {
      throw CCNavigationAdapterError(
        'GoRouter route "${route.routeId}" targets Outlet '
        '"${placement.navigatorOutlet}" without a Navigator key.',
      );
    }
    if (placement.shellId != null &&
        !_shellBindings.any((shell) => shell.shellId == placement.shellId)) {
      throw CCNavigationAdapterError(
        'GoRouter route "${route.routeId}" targets unknown Shell '
        '"${placement.shellId}".',
      );
    }
  }

  /// Retains one backend event for diagnostics without exposing mutable state.
  ///
  /// Only operations initiated by this adapter can be correlated with a
  /// Runtime request. Uncorrelated Dialog, PopupRoute, LocalHistoryEntry, and
  /// application-owned Navigator events are forwarded without reconciling the
  /// managed entry list because their stack identity is not yet known.
  void _recordLifecycleEvent(CCGoRouterNavigationEvent event) {
    if (_disposed) return;
    if (_lifecycleEventCapacity > 0) {
      if (_lifecycleEvents.length == _lifecycleEventCapacity) {
        _lifecycleEvents.removeAt(0);
      }
      _lifecycleEvents.add(event);
    }
    final isAdapterOwned = _consumeExpectedBackendEvent(event.kind);
    final matchesActiveRequest = _matchesActiveRequest(event.location);
    if (event.kind == CCGoRouterNavigationEventKind.pop) {
      final backendEntryId = _backendEntryIdFor(event.route);
      _lastPoppedBackendEntryId = backendEntryId;
      _lastPoppedOwner =
          _entries.any((entry) => entry.backendEntryId == backendEntryId)
          ? CCPopRemovedOwner.managed
          : CCPopRemovedOwner.foreign;
    }
    final observedBackendEntryId = _backendRouteIds[event.route];
    final observedManagedRoute =
        observedBackendEntryId != null &&
        _entries.any((entry) => entry.backendEntryId == observedBackendEntryId);
    final canCorrelateAdapterEvent = switch (event.kind) {
      CCGoRouterNavigationEventKind.push =>
        matchesActiveRequest ||
            (_entries.isNotEmpty &&
                _bindingFor(_entries.last.request.routeId) == null),
      CCGoRouterNavigationEventKind.pop => observedManagedRoute,
      CCGoRouterNavigationEventKind.topChanged =>
        observedManagedRoute || matchesActiveRequest,
      _ => true,
    };
    _emitBackendEvent(
      event,
      correlateRequest:
          (isAdapterOwned && canCorrelateAdapterEvent) ||
          (event.kind == CCGoRouterNavigationEventKind.push &&
              matchesActiveRequest),
    );
  }

  /// Reports foreground Stateful Shell branch changes from GoRouter state.
  ///
  /// Branch Navigators remain mounted in an indexed stack, so switching tabs
  /// does not guarantee a NavigatorObserver top callback. The RouterDelegate
  /// configuration identifies the active branch and supplies the missing Host
  /// visibility signal without treating the branch as removed.
  void _recordRouterConfigurationChange() {
    if (!_initialized || _disposed) return;
    final activation = _activeStatefulShellPlacement(
      _router.routerDelegate.currentConfiguration.matches,
    );
    if (activation == null) return;
    final shellId = activation.shellId!;
    final outlet = activation.navigatorOutlet;
    if (_activeOutletsByShell[shellId] == outlet) return;
    _activeOutletsByShell[shellId] = outlet;
    CCPageLifecycleHostBridge.setActiveOutlets(
      hostId: _hostId,
      outlets: [outlet],
    );
    final operationSequence = ++_backendOperationSequence;
    _publishBackendEvent(
      CCNavigationBackendEvent(
        kind: CCNavigationBackendEventKind.outletActivated,
        backendOperationId: '$_backendAdapterId-operation-$operationSequence',
        hostId: _hostId,
        navigatorOutlet: outlet,
        sequence: operationSequence,
        placement: activation,
        location: _router.routeInformationProvider.value.uri.toString(),
        timestamp: DateTime.now(),
      ),
    );
  }

  /// Finds the deepest active Stateful Shell placement in one match branch.
  CCRoutePlacement? _activeStatefulShellPlacement(
    List<RouteMatchBase> matches,
  ) {
    CCRoutePlacement? result;
    for (final match in matches) {
      if (match is! ShellRouteMatch) continue;
      final binding = _shellBindings.cast<CCGoRouterShellBinding?>().firstWhere(
        (candidate) =>
            candidate != null && identical(candidate.route, match.route),
        orElse: () => null,
      );
      if (binding != null && binding.route is StatefulShellRoute) {
        result = CCRoutePlacement(
          hostId: _hostId,
          shellId: binding.shellId,
          navigatorOutlet: _outletForNavigatorKey(match.navigatorKey),
        );
      }
      result = _activeStatefulShellPlacement(match.matches) ?? result;
    }
    return result;
  }

  /// Whether a backend route location identifies the active CCRouter request.
  bool _matchesActiveRequest(String? location) {
    if (location == null || _entries.isEmpty) return false;
    final request = _entries.last.request;
    final expected = _locationFor(request.uri);
    if (location == expected) return true;
    if (location == request.routeId) return true;

    // GoRouter's NavigatorObserver may expose the route-definition fragment
    // (for example, `:id`) instead of the resolved URI (`/orders/42`). Only
    // the active request's binding may claim that fragment; comparing against
    // all bindings would incorrectly associate a parent route with a child.
    final binding = _bindingFor(request.routeId);
    return binding?.goRoute.path == location;
  }

  /// Translates a Flutter observer event into the adapter-neutral contract.
  void _emitBackendEvent(
    CCGoRouterNavigationEvent event, {
    required bool correlateRequest,
  }) {
    final observedBackendEntryId =
        _backendRouteIds[event.route] ?? _claimInitialBackendEntryId(event);
    final trackedEntry = observedBackendEntryId == null
        ? null
        : _entries.cast<_CCGoRouterEntry?>().firstWhere(
            (entry) => entry?.backendEntryId == observedBackendEntryId,
            orElse: () => null,
          );
    final request = correlateRequest
        ? trackedEntry?.request ??
              (_entries.isNotEmpty ? _entries.last.request : null)
        : null;
    final trackedBackendEntryId = request == null
        ? observedBackendEntryId
        : _backendIdsByNavigationId[request.navigationId] ??
              observedBackendEntryId;
    if (trackedBackendEntryId != null) {
      _backendRouteIds[event.route] = trackedBackendEntryId;
    }
    final backendEntryId =
        trackedBackendEntryId ?? _backendEntryIdFor(event.route);
    final previousBackendEntryId = event.previousRoute == null
        ? null
        : _backendEntryIdFor(event.previousRoute!);
    final operationSequence = ++_backendOperationSequence;
    final backendEvent = CCNavigationBackendEvent(
      kind: switch (event.kind) {
        CCGoRouterNavigationEventKind.push => CCNavigationBackendEventKind.push,
        CCGoRouterNavigationEventKind.pop => CCNavigationBackendEventKind.pop,
        CCGoRouterNavigationEventKind.replace =>
          CCNavigationBackendEventKind.replace,
        CCGoRouterNavigationEventKind.remove =>
          CCNavigationBackendEventKind.remove,
        CCGoRouterNavigationEventKind.topChanged =>
          CCNavigationBackendEventKind.topChanged,
      },
      backendEntryId: backendEntryId,
      backendOperationId: '$_backendAdapterId-operation-$operationSequence',
      previousBackendEntryId: previousBackendEntryId,
      hostId: event.hostId,
      navigatorOutlet: event.outlet,
      sequence: operationSequence,
      // A correlated `remove` is the first half of GoRouter `go`/`reset` and
      // describes the previous backend page, not the newly requested route.
      // Keep it diagnostic; externally observed Pops can still use the
      // identity mapped in [_backendRouteIds].
      owner:
          trackedEntry != null && !correlateRequest ||
              request != null &&
                  event.kind != CCGoRouterNavigationEventKind.remove
          ? CCBackendEntryOwner.managed
          : CCBackendEntryOwner.foreign,
      navigationId: request?.navigationId,
      routeId: request?.routeId,
      uri: request?.uri,
      placement: request == null
          ? CCRoutePlacement(
              hostId: event.hostId,
              navigatorOutlet: event.outlet,
            )
          : _resolvedPlacement(request),
      location: event.location,
      origin: request?.origin,
      source: request?.source,
      timestamp: DateTime.now(),
    );
    _publishBackendEvent(backendEvent);
  }

  /// Binds one pre-mount snapshot identity to its concrete Navigator Route.
  ///
  /// Exact location matches are preferred. Generated CCRouter pages expose a
  /// route ID as `RouteSettings.name`, while their initial snapshot exposes a
  /// resolved path, so the first still-unbound entry in the same Outlet is the
  /// deterministic fallback during initial Navigator construction.
  String? _claimInitialBackendEntryId(CCGoRouterNavigationEvent event) {
    if (_unboundInitialBackendEntries.isEmpty ||
        event.kind != CCGoRouterNavigationEventKind.push &&
            event.kind != CCGoRouterNavigationEventKind.topChanged) {
      return null;
    }
    final exactIndex = _unboundInitialBackendEntries.indexWhere(
      (entry) =>
          entry.navigatorOutlet == event.outlet &&
          entry.location == event.location,
    );
    final outletIndex = exactIndex != -1
        ? exactIndex
        : _unboundInitialBackendEntries.indexWhere(
            (entry) => entry.navigatorOutlet == event.outlet,
          );
    if (outletIndex == -1) return null;
    final initial = _unboundInitialBackendEntries.removeAt(outletIndex);
    _backendRouteIds[event.route] = initial.backendEntryId;
    return initial.backendEntryId;
  }

  /// Copies structural placement with the request's resolved Host identity.
  ///
  /// Route contracts retain `default` as an Adapter-neutral alias, while
  /// backend diagnostics must expose one concrete Host consistently in both
  /// the event and its placement snapshot.
  CCRoutePlacement _resolvedPlacement(CCNavigationRequest request) {
    final placement = request.placement;
    return CCRoutePlacement(
      hostId: request.hostId,
      parentRouteId: placement.parentRouteId,
      shellId: placement.shellId,
      navigatorOutlet: placement.navigatorOutlet,
    );
  }

  /// Publishes one explicit third-party route transition through the Adapter.
  void _recordForeignBridgeEvent(
    CCNavigationBackendEventKind kind,
    CCGoRouterForeignRouteHandle handle,
    CCGoRouterForeignRouteHandle? previous,
  ) {
    _ensureAvailable();
    final operationSequence = ++_backendOperationSequence;
    _publishBackendEvent(
      CCNavigationBackendEvent(
        kind: kind,
        backendEntryId: handle.backendEntryId,
        backendOperationId: '$_backendAdapterId-operation-$operationSequence',
        previousBackendEntryId: previous?.backendEntryId,
        hostId: handle.hostId ?? _hostId,
        navigatorOutlet: handle.navigatorOutlet,
        sequence: operationSequence,
        owner: CCBackendEntryOwner.foreign,
        placement: CCRoutePlacement(
          hostId: handle.hostId ?? _hostId,
          navigatorOutlet: handle.navigatorOutlet,
        ),
        location: handle.location,
        timestamp: DateTime.now(),
      ),
    );
  }

  /// Flattens one GoRouter match branch while retaining its Navigator Outlet.
  void _collectInitialMatches(
    List<RouteMatchBase> matches,
    List<CCNavigationBackendEntrySnapshot> snapshots, {
    required String outlet,
  }) {
    for (final match in matches) {
      final matchOutlet = match is ShellRouteMatch
          ? _outletForNavigatorKey(match.navigatorKey)
          : outlet;
      snapshots.add(
        CCNavigationBackendEntrySnapshot(
          backendEntryId: _nextBackendEntryId(),
          owner: CCBackendEntryOwner.opaque,
          hostId: _hostId,
          navigatorOutlet: matchOutlet,
          location: match.matchedLocation,
        ),
      );
      if (match is ShellRouteMatch) {
        _collectInitialMatches(match.matches, snapshots, outlet: matchOutlet);
      }
    }
  }

  /// Resolves an application-owned Navigator key to its configured Outlet.
  String _outletForNavigatorKey(GlobalKey<NavigatorState> key) {
    if (identical(key, _router.routerDelegate.navigatorKey)) return 'root';
    for (final entry in _navigatorKeys.entries) {
      if (identical(entry.value, key)) return entry.key;
    }
    return 'root';
  }

  /// Publishes one opaque UI transition without creating a managed route.
  ///
  /// Opaque surfaces include overlays, menus, `LocalHistoryEntry`, and
  /// third-party popup systems whose lifecycle cannot be represented as a
  /// Navigator `Route`. They remain isolated from RouteEntry and result
  /// bookkeeping while still appearing in backend diagnostics.
  void _recordOpaqueBridgeEvent(
    CCNavigationBackendEventKind kind,
    CCGoRouterOpaqueUiHandle handle,
  ) {
    _ensureAvailable();
    final operationSequence = ++_backendOperationSequence;
    _publishBackendEvent(
      CCNavigationBackendEvent(
        kind: kind,
        backendEntryId: handle.backendEntryId,
        backendOperationId: '$_backendAdapterId-operation-$operationSequence',
        hostId: handle.hostId ?? _hostId,
        navigatorOutlet: handle.navigatorOutlet,
        sequence: operationSequence,
        owner: CCBackendEntryOwner.opaque,
        placement: CCRoutePlacement(
          hostId: handle.hostId ?? _hostId,
          navigatorOutlet: handle.navigatorOutlet,
        ),
        location: handle.location,
        timestamp: DateTime.now(),
      ),
    );
  }

  /// Notifies backend listeners while isolating telemetry failures.
  void _publishBackendEvent(CCNavigationBackendEvent backendEvent) {
    for (final listener in _backendListeners.toList()) {
      try {
        listener(backendEvent);
      } catch (_) {
        // Backend telemetry must never interrupt a Navigator transition.
      }
    }
  }

  /// Validates Shell contracts against application-owned GoRouter bindings.
  void _validateShellBindings(List<CCNavigationShell> contracts) {
    final bindingsById = <String, CCGoRouterShellBinding>{};
    for (final binding in _shellBindings) {
      if (bindingsById.containsKey(binding.shellId)) {
        throw CCNavigationAdapterError(
          'Duplicate GoRouter Shell binding "${binding.shellId}".',
        );
      }
      bindingsById[binding.shellId] = binding;
    }
    final contractIds = contracts.map((shell) => shell.shellId).toSet();
    final unknownBindings = bindingsById.keys.toSet().difference(contractIds);
    if (unknownBindings.isNotEmpty) {
      final ids = unknownBindings.toList()..sort();
      throw CCNavigationAdapterError(
        'GoRouter Shell bindings have no Runtime contract: ${ids.join(', ')}.',
      );
    }
    for (final contract in contracts) {
      final binding = bindingsById[contract.shellId];
      if (binding == null) {
        throw CCNavigationAdapterError(
          'Runtime Shell "${contract.shellId}" has no GoRouter binding.',
        );
      }
      final boundOutlets = binding.outlets.keys.toList();
      if (!_sameOrder(boundOutlets, contract.outlets)) {
        throw CCNavigationAdapterError(
          'GoRouter Shell "${contract.shellId}" Outlet order does not match '
          'the Runtime contract.',
        );
      }
      if (binding.initialOutlet != contract.initialOutlet) {
        throw CCNavigationAdapterError(
          'GoRouter Shell "${contract.shellId}" initial Outlet '
          '"${binding.initialOutlet}" does not match Runtime Outlet '
          '"${contract.initialOutlet}".',
        );
      }
      switch (contract.type) {
        case CCShellType.singleNavigator:
          final route = binding.route;
          if (route is! ShellRoute ||
              binding.outlets.length != 1 ||
              !identical(
                binding.outlets[contract.outlets.single],
                route.navigatorKey,
              )) {
            throw CCNavigationAdapterError(
              'Single-Navigator Shell "${contract.shellId}" must bind its '
              'ShellRoute Navigator key to Outlet '
              '"${contract.outlets.single}".',
            );
          }
          break;
        case CCShellType.statefulBranches:
          final route = binding.route;
          if (route is! StatefulShellRoute ||
              route.branches.length != contract.outlets.length) {
            throw CCNavigationAdapterError(
              'Stateful Shell "${contract.shellId}" must bind one '
              'StatefulShellRoute branch per declared Outlet.',
            );
          }
          for (var index = 0; index < contract.outlets.length; index++) {
            final outlet = contract.outlets[index];
            if (!identical(
              binding.outlets[outlet],
              route.branches[index].navigatorKey,
            )) {
              throw CCNavigationAdapterError(
                'Stateful Shell "${contract.shellId}" branch $index does '
                'not match Outlet "$outlet".',
              );
            }
          }
      }
    }
  }

  /// Compares ordered string identities without allocating converted sets.
  static bool _sameOrder(List<String> first, List<String> second) {
    if (first.length != second.length) return false;
    for (var index = 0; index < first.length; index++) {
      if (first[index] != second[index]) return false;
    }
    return true;
  }

  /// Combines explicit Outlet keys with keys declared by Shell bindings.
  static Map<String, GlobalKey<NavigatorState>> _mergeNavigatorKeys(
    Map<String, GlobalKey<NavigatorState>> explicit,
    Iterable<CCGoRouterShellBinding> shells,
  ) {
    final merged = <String, GlobalKey<NavigatorState>>{...explicit};
    for (final shell in shells) {
      for (final entry in shell.outlets.entries) {
        final existing = merged[entry.key];
        if (existing != null && !identical(existing, entry.value)) {
          throw ArgumentError.value(
            entry.key,
            'navigatorKeys',
            'Outlet is declared with different Navigator keys.',
          );
        }
        merged[entry.key] = entry.value;
      }
    }
    return Map.unmodifiable(merged);
  }

  /// Ensures Shell bindings do not introduce keys outside the immutable Host.
  static void _validateHostNavigatorKeys(
    CCNavigationHost host,
    Map<String, GlobalKey<NavigatorState>> merged,
  ) {
    for (final entry in merged.entries) {
      if (!host.containsOutlet(entry.key) ||
          !identical(host.navigatorKeyFor(entry.key), entry.value)) {
        throw ArgumentError.value(
          entry.key,
          'shells',
          'Shell Outlet must use the Navigator key registered by Host '
              '"${host.id}".',
        );
      }
    }
  }

  /// Validates that every Observer belongs to this Adapter's Host and Outlet.
  static void _validateObserverBindings(
    String hostId,
    Map<String, GlobalKey<NavigatorState>> navigatorKeys,
    Iterable<CCGoRouterNavigationObserver> observers,
  ) {
    for (final observer in observers) {
      if (observer.hostId != hostId) {
        throw ArgumentError.value(
          observer.hostId,
          'observers',
          'Observer Host does not match Adapter Host "$hostId".',
        );
      }
      if (observer.outlet != 'root' &&
          !navigatorKeys.containsKey(observer.outlet)) {
        throw ArgumentError.value(
          observer.outlet,
          'observers',
          'Observer Outlet has no registered Navigator key.',
        );
      }
    }
  }

  /// Finds the Navigator belonging to the currently tracked route.
  NavigatorState? get _activeNavigator {
    final key = _entries.isEmpty
        ? null
        : _navigatorKeys[_entries.last.request.placement.navigatorOutlet];
    return key?.currentState ??
        _router.routerDelegate.navigatorKey.currentState;
  }
}

/// Internal snapshot used by stack predicates without exposing GoRouter types.
final class _CCGoRouterEntry {
  /// Creates a tracked entry from one accepted navigation request.
  ///
  /// [exposesResult] is true only when Runtime returned the result Future to a
  /// caller. Entries used for dynamic opens and location changes retain stack
  /// identity without creating an error-producing business result channel.
  _CCGoRouterEntry(
    this.request,
    this.backendEntryId, {
    required bool exposesResult,
  }) : _resultCompleter = exposesResult ? Completer<Object?>() : null;

  /// Request that created this tracked entry.
  final CCNavigationRequest request;

  /// Backend identity associated with the GoRouter Route for this entry.
  final String backendEntryId;

  /// Optional Adapter-owned result channel independent of match retention.
  final Completer<Object?>? _resultCompleter;

  /// Result Future returned to Runtime for this managed navigation.
  Future<Object?> get result => _resultCompleter?.future ?? Future.value();

  /// Completes the managed result exactly once.
  void completeResult(Object? value) {
    final completer = _resultCompleter;
    if (completer != null && !completer.isCompleted) completer.complete(value);
  }

  /// Completes the managed result with one backend failure exactly once.
  void completeError(Object error, StackTrace stackTrace) {
    final completer = _resultCompleter;
    if (completer != null && !completer.isCompleted) {
      completer.completeError(error, stackTrace);
    }
  }
}

/// Initial backend identity awaiting a concrete Flutter Route association.
final class _CCInitialBackendEntry {
  /// Creates one pending initial backend association.
  const _CCInitialBackendEntry({
    required this.backendEntryId,
    required this.navigatorOutlet,
    required this.location,
  });

  /// Adapter-scoped backend identity already imported by Runtime.
  final String backendEntryId;

  /// Navigator Outlet that owns the initial entry.
  final String navigatorOutlet;

  /// Resolved location captured from GoRouter's initial match tree.
  final String? location;
}
